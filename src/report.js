function color(score) {
  return score >= 75 ? "var(--g)" : score >= 55 ? "var(--n)" : "var(--c)";
}

function issueBlock(c, extra = "") {
  const chips = [c.evidence, c.section ? `Guide §${c.section}` : "", c.group ? A11Y_GROUPS[c.group] : ""].filter(Boolean);
  return `<div class="issue ${esc(c.severity)}"><p><span class="sev ${esc(c.severity)}">${esc(c.severity)}</span> <strong>${esc(c.title)}</strong></p>
<p class="muted">${esc(c.detail)}</p>${c.fix ? `<p class="fix"><strong>Fix:</strong> ${esc(c.fix)}</p>` : ""}${c.suggested ? `<pre>${esc(c.suggested)}</pre>` : ""}
${extra}<p>${chips.map((t) => `<span class="chip">${esc(t)}</span>`).join("")}${c.helpUrl ? ` <a href="${esc(c.helpUrl)}">Rule details</a>` : ""}</p></div>`;
}

function sortIssues(list) {
  return [...list].sort((a, b) => SEV_ORDER[a.severity] - SEV_ORDER[b.severity]);
}

function scoreBoxes(items) {
  return `<div class="scores">${items.map(([label, score, sub]) => `<div class="score"><span class="muted">${esc(label)}</span><b style="color:${score == null ? "var(--m)" : color(score)}">${score == null ? "–" : score}</b><span class="muted">${esc(sub || "")}</span></div>`).join("")}</div>`;
}

function doc(title, body) {
  return `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>${esc(title)}</title><style>${CSS}</style></head><body><div class="wrap">${body}
<p class="muted" style="margin-top:40px">Generated by AEO Scorer. Rules follow "AEO &amp; GEO: A Developer's Implementation Guide" (Nov 2026); accessibility checks use axe-core against WCAG 2.2 A/AA. There is no industry-standard AEO score.</p></div></body></html>`;
}

/** Single page report. */
export function pageReportHtml({ url, title, result, a11y, ai, at }) {
  const failing = result.checks.filter((c) => !c.pass && c.severity !== "info");
  const notes = result.checks.filter((c) => c.severity === "info");
  const byArea = (area) => sortIssues(failing.filter((c) => areaOf(c.category) === area));
  const aiFindings = ai?.review?.findings || [];

  let body = `<h1>AEO report: ${esc(title || url)}</h1><p class="muted"><a href="${esc(url)}">${esc(url)}</a> · ${esc(new Date(at || Date.now()).toLocaleString())}</p>`;
  body += scoreBoxes([
    ["AEO score", result.score, result.grade],
    ["Accessibility", a11y?.score ?? null, a11y ? `${a11y.checks.length} rules failing` : "not run"],
    ["Claude content score", ai?.review?.semantic_score ?? null, ai ? ai.model : "not run"],
    ["Issues to fix", failing.length + (a11y?.checks.length || 0) + aiFindings.length, ""],
  ]);
  body += `<h2>Score by area</h2><table><tr><th>Area</th><th>Checks passed</th><th style="width:40%">Score</th></tr>${Object.values(result.categories)
    .map((c) => `<tr><td>${esc(c.label)} <span class="muted">(${c.weight}%)</span></td><td>${c.passed}/${c.total}</td><td><div class="bar"><span style="width:${c.score}%;background:${color(c.score)}"></span></div>${c.score}%</td></tr>`)
    .join("")}</table>`;

  if (ai?.review) {
    body += `<h2>Claude review</h2><p><strong>Main question:</strong> ${esc(ai.review.primary_question)}</p><p>${esc(ai.review.summary)}</p>`;
    body += sortIssues(aiFindings).map((f) => issueBlock({ severity: f.severity, title: f.title, detail: f.problem, fix: f.fix, suggested: f.suggested_text, evidence: `Claude · ${f.category}` })).join("");
    if (ai.review.suggested_json_ld) body += `<h3>Suggested JSON-LD</h3><pre>${esc(ai.review.suggested_json_ld)}</pre>`;
  }
  if (result.blockers?.length) body += `<p style="color:var(--c)"><strong>Score capped at 59 (from ${result.rawScore})</strong> until these blockers are fixed: ${esc(result.blockers.join("; "))}.</p>`;
  for (const area of ["aeo", "schema", "tech"]) {
    const list = byArea(area);
    body += `<h2>${esc(AREAS[area])} (${list.length})</h2>${list.length ? list.map((c) => issueBlock(c)).join("") : '<p class="muted">No issues.</p>'}`;
  }
  if (a11y) {
    body += `<h2>Accessibility (${a11y.checks.length})</h2><p class="muted">${a11y.passedRules} rules passed. Issues are grouped by who they affect. Automated checks find roughly a third to half of accessibility problems; test with a keyboard and a screen reader too.</p>`;
    for (const [key, label] of Object.entries(A11Y_GROUPS)) {
      const list = sortIssues(a11y.checks.filter((c) => c.group === key));
      if (!list.length) continue;
      body += `<h3>${esc(label)} (${list.length})</h3>` + list.map((c) => issueBlock(c, c.items?.length ? `<p class="muted">Elements: ${c.items.slice(0, 5).map((i) => `<code>${esc(i.selector)}</code>`).join(", ")}${c.nodeCount > 5 ? ` and ${c.nodeCount - 5} more` : ""}</p>` : "")).join("");
    }
  }
  if (notes.length) body += `<h2>Notes</h2>` + notes.map((c) => `<p><strong>${esc(c.title)}:</strong> ${esc(c.detail)}</p>`).join("");
  const passed = result.checks.filter((c) => c.pass && c.severity !== "info");
  body += `<h2>Passed checks (${passed.length})</h2><ul>${passed.map((c) => `<li>${esc(c.title)}</li>`).join("")}</ul>`;
  return doc(`AEO report – ${title || url}`, body);
}

/** Aggregate failing checks across crawled pages. */
export function siteIssues(pages) {
  const map = new Map();
  for (const p of pages) {
    for (const c of p.issues || []) {
      const key = c.id.startsWith("answer-first:") ? "answer-first" : c.id;
      let e = map.get(key);
      if (!e) {
        e = { key, ...c, title: key === "answer-first" ? "Sections that do not start with a direct answer" : c.title, pages: [] };
        map.set(key, e);
      }
      if (!e.pages.includes(p.url)) e.pages.push(p.url);
      if (SEV_ORDER[c.severity] < SEV_ORDER[e.severity]) e.severity = c.severity;
    }
  }
  return [...map.values()].sort((a, b) => SEV_ORDER[a.severity] - SEV_ORDER[b.severity] || b.pages.length - a.pages.length);
}

export function siteReportHtml(site) {
  const ok = site.pages.filter((p) => !p.error);
  const issues = [...(site.siteChecks || []), ...siteIssues(ok)];
  let body = `<h1>Site AEO report: ${esc(site.origin)}</h1><p class="muted">${ok.length} pages crawled from <a href="${esc(site.startUrl)}">${esc(site.startUrl)}</a> · ${esc(new Date(site.finishedAt || Date.now()).toLocaleString())}</p>`;
  body += scoreBoxes([
    ["Average AEO score", site.avgScore, `${ok.length} pages`],
    ["Average accessibility", site.avgA11y, ""],
    ["Distinct issues", issues.length, `${issues.filter((i) => i.severity === "critical").length} critical`],
  ]);
  body += `<h2>Pages</h2><table><tr><th>Page</th><th>AEO</th><th>Accessibility</th><th>Issues</th></tr>${[...site.pages]
    .sort((a, b) => (a.score ?? 101) - (b.score ?? 101))
    .map((p) => `<tr><td><a href="${esc(p.url)}">${esc(p.title || p.url)}</a><br><span class="muted">${esc(p.url)}</span></td><td>${p.error ? "error" : `<b style="color:${color(p.score)}">${p.score}</b>`}</td><td>${p.a11yScore ?? "–"}</td><td>${p.error ? esc(p.error) : (p.issues || []).length}</td></tr>`)
    .join("")}</table>`;
  for (const area of ["aeo", "schema", "tech", "a11y"]) {
    const list = issues.filter((i) => areaOf(i.category) === area);
    body += `<h2>${esc(AREAS[area])}: issues across the site (${list.length})</h2>`;
    body += list.length
      ? list.map((i) => issueBlock(i, `<p class="muted">On ${i.pages.length} of ${ok.length} pages: ${i.pages.slice(0, 6).map((u) => `<a href="${esc(u)}">${esc(new URL(u).pathname || "/")}</a>`).join(", ")}${i.pages.length > 6 ? ` and ${i.pages.length - 6} more` : ""}</p>`)).join("")
      : '<p class="muted">No issues.</p>';
  }
  return doc(`Site AEO report – ${site.origin}`, body);
}

function csvCell(v) {
  const s = String(v ?? "");
  return /[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
}

export function issuesCsv(rows) {
  const head = ["page_url", "area", "category", "severity", "issue", "detail", "how_to_fix", "evidence", "guide_section", "wcag", "who_it_affects", "pages_affected"];
  const lines = [head.join(",")];
  for (const r of rows) {
    lines.push(
      [r.url, AREAS[areaOf(r.category)], r.category === "a11y" ? "Accessibility" : CATEGORIES[r.category]?.label || r.category, r.severity, r.title, r.detail, r.fix, r.evidence, r.section, (r.wcag || []).join(" "), r.group ? A11Y_GROUPS[r.group] : "", r.pagesAffected ?? ""]
        .map(csvCell)
        .join(","),
    );
  }
  return "﻿" + lines.join("\r\n");
}

export function download(filename, content, type) {
  const url = URL.createObjectURL(new Blob([content], { type }));
  const a = Object.assign(document.createElement("a"), { href: url, download: filename });
  document.body.append(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 10_000);
}

export function slug(s) {
  return String(s).replace(/^https?:\/\//, "").replace(/[^a-z0-9]+/gi, "-").replace(/^-|-$/g, "").slice(0, 60).toLowerCase();
}
